@patch("qfzz.dj.ai_dj.TTSClient")
def test_ai_dj_synthesize_speech_enabled(
    mock_tts_client,
    temp_personas_config,
    mock_llm_router_success,
    mock_state_manager,
):
    """Test that TTS can be enabled."""
    tts_instance = MagicMock()
    tts_instance.is_available.return_value = True
    tts_instance.synthesize.return_value = b"audio_data"
    mock_tts_client.return_value = tts_instance

    dj = AIDJ(
        persona="energetic",
        enable_tts=True,
        personas_config_path=temp_personas_config,
    )

    audio = dj.synthesize_speech("Hello world")

    assert audio == b"audio_data"
    tts_instance.synthesize.assert_called_once_with("Hello world", voice_id="alloy")


