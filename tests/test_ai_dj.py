def test_ai_dj_fallback_on_llm_failure(temp_personas_config, mock_state_manager):
    """Test AI DJ uses fallback when LLM fails."""
    with patch("qfzz.dj.ai_dj.LLMRouter") as mock_router:
        router_instance = MagicMock()
        # LLM fails
        router_instance.generate.return_value = LLMResponse(
            content="",
            provider="none",
            model="",
            cost=0.0,
            latency=0.0,
            success=False,
            error="All providers failed",
        )
        mock_router.return_value = router_instance

        dj = AIDJ(persona="energetic", personas_config_path=temp_personas_config)

        track = {"title": "Test Song", "artist": "Test Artist", "genre": "Rock"}
        intro = dj.introduce_track(track)

        # Should get fallback intro
        assert len(intro) > 0
        assert "Test Song" in intro or "Test Artist" in intro


